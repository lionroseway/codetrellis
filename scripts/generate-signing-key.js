#!/usr/bin/env node
/**
 * Mint the release-manifest signing keypair. Run ONCE, ever.
 *
 * WHAT THIS IS FOR (Phase 19, finding 23)
 *
 * The app verifies a downloaded installer against a sha256. Until now that
 * digest came from the GitHub API — which means GitHub is in the trust chain.
 * Anyone who took over the releases repo could publish a bad binary AND a
 * matching digest, and every check would pass.
 *
 * Signing the manifest takes GitHub out of it. The private key lives on one
 * machine and never goes near CI; the public key ships inside the app.
 *
 * THE TWO HALVES
 *
 *   private  scripts/release-signing-key.pem  — gitignored, 0600, THIS MACHINE
 *   public   src/backend/services/release-public-key.ts — COMMITTED, on purpose
 *
 * The public half being in the repo is the point: a running copy has to be
 * able to check a download without asking anybody.
 *
 * IF THE PRIVATE KEY IS LOST
 *
 * You cannot re-mint the same one. You generate a new pair, ship the new
 * public key in an app update, and every copy older than that update can no
 * longer verify new releases — they fall back to the browser download. So back
 * it up somewhere you would also keep the Apple credentials.
 */

const { generateKeyPairSync } = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const REPO_ROOT = path.resolve(__dirname, '..');
const PRIVATE_PATH = path.join(REPO_ROOT, 'scripts', 'release-signing-key.pem');
const PUBLIC_TS = path.join(REPO_ROOT, 'src', 'backend', 'services', 'release-public-key.ts');

if (fs.existsSync(PRIVATE_PATH) && !process.argv.includes('--force')) {
  console.error(`Refusing to overwrite ${path.relative(REPO_ROOT, PRIVATE_PATH)}.`);
  console.error('A new key invalidates every release the old one signed, and every');
  console.error('installed copy that carries the old public key. Pass --force only if');
  console.error('you mean exactly that.');
  process.exit(1);
}

// Ed25519: small keys, small signatures, no parameter choices to get wrong,
// and node:crypto verifies it with no dependency — which matters, because the
// verifier ships inside the app.
const { privateKey, publicKey } = generateKeyPairSync('ed25519');

fs.writeFileSync(
  PRIVATE_PATH,
  privateKey.export({ type: 'pkcs8', format: 'pem' }),
  { mode: 0o600 },
);

const publicPem = publicKey.export({ type: 'spki', format: 'pem' }).toString();

fs.writeFileSync(PUBLIC_TS, `/**
 * Public half of the release-manifest signing key.
 *
 * COMMITTED ON PURPOSE. A running copy of CodeTrellis has to be able to check
 * that a downloaded installer is one we published, without asking a server
 * whose answer it would then have to trust.
 *
 * The private half lives on the release machine only (gitignored), and is
 * never in CI. Generated by \`scripts/generate-signing-key.js\` — do not edit
 * this file by hand.
 *
 * Replacing this key is a breaking change for anyone running an older build:
 * they carry the old public key and will not be able to verify releases signed
 * with the new one.
 */
export const RELEASE_PUBLIC_KEY_PEM = \`${publicPem.trim()}\n\`;
`);

console.log(`Private key → ${path.relative(REPO_ROOT, PRIVATE_PATH)}  (0600, gitignored)`);
console.log(`Public key  → ${path.relative(REPO_ROOT, PUBLIC_TS)}  (commit this)`);
console.log('\nBack the private key up where you keep the Apple credentials.');
