#!/usr/bin/env node
/**
 * Generates `src/shared/build-info.ts` with packaging-time metadata
 * so the running app can show what it actually is — version, build
 * time, git commit, build number. Imported by both the backend
 * (`/api/build-info` REST) and the frontend (Settings → About).
 *
 * Idempotent: re-runs always overwrite. Designed to run in two
 * places:
 *   - **`npm run package`**: via the `prepackage` npm script. Picks
 *     the build time = now, commit = current HEAD, so every
 *     DMG / EXE / DEB carries fresh metadata.
 *   - **Dev / typecheck**: the file is committed with sensible
 *     defaults (version from package.json) so it's never missing on
 *     a fresh clone.
 *
 * Build number policy: count of commits reachable from HEAD. Stable,
 * monotonic, no external counter required. Falls back to 0 if we
 * can't run git.
 */

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const REPO_ROOT = path.resolve(__dirname, '..');
const TARGET = path.join(REPO_ROOT, 'src', 'shared', 'build-info.ts');
const PKG = JSON.parse(fs.readFileSync(path.join(REPO_ROOT, 'package.json'), 'utf-8'));

function safeGit(args) {
  try {
    return execFileSync('git', args, { cwd: REPO_ROOT, encoding: 'utf-8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return '';
  }
}

const version = PKG.version;
const buildTime = new Date().toISOString();
const commit = safeGit(['rev-parse', 'HEAD']);
const commitShort = commit ? commit.slice(0, 7) : '';
const branch = safeGit(['rev-parse', '--abbrev-ref', 'HEAD']);
const buildNumberRaw = safeGit(['rev-list', '--count', 'HEAD']);
const buildNumber = buildNumberRaw ? Number(buildNumberRaw) : 0;
// Was the working tree clean at build time? Useful when chasing
// "why does this DMG behave differently" — dirty builds aren't
// reproducible from a tag.
// Ignore THIS file's own pending change. The script rewrites build-info.ts
// every time it runs, so counting it makes a release built from a spotless
// tree still report `dirty: true` — which tells whoever is debugging a DMG
// exactly the wrong thing about where it came from.
const dirty = safeGit(['status', '--porcelain'])
  .split('\n')
  .map((line) => line.trim())
  .filter((line) => line !== '' && !line.endsWith('src/shared/build-info.ts'))
  .length > 0;

const ts = `/**
 * Auto-generated by scripts/generate-build-info.js — DO NOT EDIT BY HAND.
 *
 * The file IS committed (rather than gitignored) so:
 *   - typecheck doesn't fail on a fresh clone before the prebuild
 *     hook has run
 *   - the dev backend (run via tsx) can import it without an extra
 *     build step
 *
 * The \`prepackage\` npm script re-runs this at packaging time so
 * the DMG / EXE always carries fresh metadata.
 */
export interface BuildInfo {
  version: string;
  buildTime: string;       // ISO 8601
  buildNumber: number;     // commit count from HEAD; monotonic
  commit: string;          // full SHA
  commitShort: string;     // 7-char SHA
  branch: string;
  dirty: boolean;          // working tree had uncommitted changes at build
}

export const BUILD_INFO: BuildInfo = ${JSON.stringify({
  version,
  buildTime,
  buildNumber,
  commit,
  commitShort,
  branch,
  dirty,
}, null, 2)};
`;

fs.writeFileSync(TARGET, ts, 'utf-8');
console.log(`[build-info] Wrote ${path.relative(REPO_ROOT, TARGET)} — v${version} build #${buildNumber} ${commitShort}${dirty ? ' (dirty)' : ''}`);
